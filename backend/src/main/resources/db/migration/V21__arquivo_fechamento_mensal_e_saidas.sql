CREATE TABLE fechamento_mensal_arquivos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    empreendimento_id BIGINT NOT NULL REFERENCES empreendimentos(id),
    mes VARCHAR(7) NOT NULL,
    relatorio_json TEXT NOT NULL,
    criado_por_usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_fechamento_arquivado UNIQUE (empresa_id, empreendimento_id, mes)
);
CREATE INDEX idx_fechamento_arquivos_empresa ON fechamento_mensal_arquivos(empresa_id, mes DESC);

