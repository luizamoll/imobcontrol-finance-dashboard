CREATE TABLE fechamento_mensal_lancamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    empreendimento_id BIGINT NOT NULL REFERENCES empreendimentos(id),
    data_lancamento DATE NOT NULL,
    tipo VARCHAR(35) NOT NULL,
    descricao VARCHAR(240) NOT NULL,
    valor NUMERIC(19,2) NOT NULL,
    criado_por_usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estornado_por_usuario_id BIGINT REFERENCES usuarios(id),
    estornado_em TIMESTAMP,
    CONSTRAINT chk_fechamento_valor_positivo CHECK (valor > 0),
    CONSTRAINT chk_fechamento_tipo CHECK (tipo IN (
        'CUSTO_EMPREENDIMENTO', 'IMPOSTO_PAGO', 'DISTRATO_DEVOLUCAO',
        'RETENCAO', 'OUTRA_RECEITA'
    ))
);
CREATE INDEX idx_fechamento_empresa_mes
    ON fechamento_mensal_lancamentos (empresa_id, data_lancamento, empreendimento_id);
