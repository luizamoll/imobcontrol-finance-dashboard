CREATE TABLE revisoes_financeiras_vendas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id BIGINT NOT NULL REFERENCES empresas(id),
  venda_id BIGINT NOT NULL REFERENCES vendas(id),
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  justificativa VARCHAR(1000) NOT NULL,
  versao_anterior BIGINT NOT NULL,
  versao_nova BIGINT NOT NULL,
  resumo_anterior TEXT NOT NULL,
  resumo_novo TEXT NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_revisoes_financeiras_vendas ON revisoes_financeiras_vendas(empresa_id, venda_id, id DESC);