CREATE TABLE reajustes_venda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    venda_id BIGINT NOT NULL,
    data_referencia DATE NOT NULL,
    percentual_aplicado NUMERIC(9,4) NOT NULL,
    indice_referencia VARCHAR(80),
    criado_por_usuario_id BIGINT NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reajustes_venda_empresa FOREIGN KEY (empresa_id) REFERENCES empresas(id),
    CONSTRAINT fk_reajustes_venda_venda FOREIGN KEY (venda_id) REFERENCES vendas(id),
    CONSTRAINT fk_reajustes_venda_usuario FOREIGN KEY (criado_por_usuario_id) REFERENCES usuarios(id),
    CONSTRAINT uk_reajustes_venda_ciclo UNIQUE (empresa_id, venda_id, data_referencia)
);

CREATE INDEX idx_reajustes_venda_empresa_venda
    ON reajustes_venda(empresa_id, venda_id, data_referencia);
