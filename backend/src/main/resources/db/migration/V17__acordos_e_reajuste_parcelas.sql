CREATE TABLE acordos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    venda_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    data_acordo DATE NOT NULL,
    valor_original NUMERIC(19,2) NOT NULL,
    valor_acordo NUMERIC(19,2) NOT NULL,
    entrada_valor NUMERIC(19,2) NOT NULL DEFAULT 0,
    quantidade_parcelas INTEGER NOT NULL,
    primeiro_vencimento DATE NOT NULL,
    observacoes TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'ativo',
    criado_por_usuario_id BIGINT NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_acordos_empresa FOREIGN KEY (empresa_id) REFERENCES empresas(id),
    CONSTRAINT fk_acordos_venda FOREIGN KEY (venda_id) REFERENCES vendas(id),
    CONSTRAINT fk_acordos_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(id),
    CONSTRAINT fk_acordos_usuario FOREIGN KEY (criado_por_usuario_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_acordos_empresa_venda ON acordos(empresa_id, venda_id, data_acordo);

